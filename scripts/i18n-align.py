# interpolation-token sanity: vars in en must match vars in translations
import re
def vars_of(s):
    return sorted(re.findall(r'\{(\w+)\}', s))
problems = []
for loc in ['es', 'sw', 'fr']:
    d = json.load(open(f'lib/i18n/messages/{loc}.json', encoding='utf-8'))
    for k, v in d.items():
        if k in en and vars_of(en[k]) != vars_of(v):
            problems.append((loc, k, vars_of(en[k]), vars_of(v)))
print('interpolation mismatches:', len(problems))
for p in problems:
    print(' ', p)
